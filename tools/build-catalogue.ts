// The only place that reads the research file (gitignored, under .dev/). Tests and the CLI never do.
// Usage: node tools/build-catalogue.ts [--research <file>] [--check] [--strict]
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parse, stringify } from "yaml";
import { validateAuthored, validateLoadFacts, validatePractices, validateSources } from "../src/catalog/schema.ts";
import { buildCatalogue } from "./catalogue/build.ts";
import type { Authored, Overlays } from "./catalogue/build.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalogDir = join(root, "catalog");
const authoredDir = join(catalogDir, "authored");

const { values } = parseArgs({
  options: { research: { type: "string" }, check: { type: "boolean" }, strict: { type: "boolean" } },
  strict: true,
});
const researchPath = values.research ?? join(root, ".dev", "research", "anthropic-best-practices.md");
if (!existsSync(researchPath)) {
  console.error(`research file not found: ${researchPath}`);
  process.exit(2);
}

function readMap<T>(file: string): Record<string, T> {
  return (parse(readFileSync(join(authoredDir, file), "utf8")) ?? {}) as Record<string, T>;
}

function readPractices(): Record<string, Authored> {
  const merged: Record<string, Authored> = {};
  const dir = join(authoredDir, "practices");
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".yaml")).sort())
    for (const [id, a] of Object.entries((parse(readFileSync(join(dir, f), "utf8")) ?? {}) as Record<string, Authored>)) {
      if (id in merged) throw new Error(`${id} is authored twice (second time in ${f})`);
      merged[id] = a;
    }
  return merged;
}

const overlays: Overlays = {
  overrides: readMap("overrides.yaml"),
  quotes: readMap("quotes.yaml"),
  experimental: readMap("experimental.yaml"),
  sources: readMap("sources.yaml"),
  practices: readPractices(),
};
const built = buildCatalogue(readFileSync(researchPath, "utf8"), overlays);

for (const w of built.warnings) console.error(`warning: ${w}`);
const problems = [...validateSources(built.sources), ...validateLoadFacts(built.load_facts), ...validatePractices(built.practices, new Set(built.sources.map((s) => s.id)))];
const authoredProblems = validateAuthored(built.practices);
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(2);
}
if (authoredProblems.length > 0) {
  console.error(`${authoredProblems.length} authoring problem(s):\n  ${authoredProblems.slice(0, 40).join("\n  ")}`);
  if (values.strict) process.exit(2);
}

const header = "# GENERATED by tools/build-catalogue.ts from research revision {rev}. Do not edit: change catalog/authored/ and run `npm run catalog:build`.\n";
const files: Record<string, string> = {
  "meta.yaml": header.replace("{rev}", String(built.meta.revision)) + stringify(built.meta, { lineWidth: 0 }),
  "sources.yaml": header.replace("{rev}", String(built.meta.revision)) + stringify(built.sources, { lineWidth: 0 }),
  "load-facts.yaml": header.replace("{rev}", String(built.meta.revision)) + stringify(built.load_facts, { lineWidth: 0 }),
  "practices.yaml": header.replace("{rev}", String(built.meta.revision)) + stringify(built.practices, { lineWidth: 0, aliasDuplicateObjects: false }),
};
files["practices.sha256"] = createHash("sha256").update(files["practices.yaml"]!).digest("hex") + "\n";
let differs = false;
for (const [name, text] of Object.entries(files)) {
  const path = join(catalogDir, name);
  if (values.check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== text) {
      console.error(`${name} is out of date`);
      differs = true;
    }
  } else writeFileSync(path, text);
}
if (values.check) process.exit(differs ? 1 : 0);
console.log(`wrote ${built.practices.length} practices and ${built.sources.length} sources`);
